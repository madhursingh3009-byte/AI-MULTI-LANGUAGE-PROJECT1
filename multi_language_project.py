import gradio as gr

def enhanced_translate(text, target_language_name):
    if not text.strip():
        return "", "Please enter text to translate."

    # 1. Detect source language
    src_lang_code = detect_language(text)

    # 2. Get target language code from mapping
    tgt_lang_code = M2M_100_LANGUAGES.get(target_language_name, "en")

    # 3. Perform translation
    translation = translate_text(text, src_lang_code, tgt_lang_code)

    status = f"Detected Source: {src_lang_code.upper()} | Translated to: {target_language_name}"
    return translation, status

