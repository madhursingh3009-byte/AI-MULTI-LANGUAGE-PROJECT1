from transformers import M2M100ForConditionalGeneration, M2M100Tokenizer
import torch

# Initialize M2M100 model and tokenizer
model_name = "facebook/m2m100_418M"
tokenizer = M2M100Tokenizer.from_pretrained(model_name)
model = M2M100ForConditionalGeneration.from_pretrained(model_name)

# Check if CUDA is available and move model to GPU if it is
device = "cuda" if torch.cuda.is_available() else "cpu"
model.to(device)

def translate_text(text, source_lang_code, target_lang_code):
    """
    Translates text from source_lang_code to target_lang_code using M2M100 model.
    """
    tokenizer.src_lang = source_lang_code
    encoded_text = tokenizer(text, return_tensors="pt").to(device)
    generated_tokens = model.generate(**encoded_text, forced_bos_token_id=tokenizer.get_lang_id(target_lang_code))
    return tokenizer.batch_decode(generated_tokens, skip_special_tokens=True)[0]



